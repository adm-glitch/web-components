class FdState extends HTMLElement {
  static get observedAttributes() { return STATE_ATTRS; }
  constructor() { super(); this.attachShadow({ mode: 'open' }); }
  connectedCallback() { this.render(); }
  disconnectedCallback() { clearTimeout(this._slow); }
  attributeChangedCallback() { if (this.isConnected) this.render(); }
  render() {
    const kind = this.getAttribute('kind') || 'empty';
    const k = ['mq', 'at', 'ps'].includes(this.getAttribute('company')) ? this.getAttribute('company') : 'ps';
    const name = this.getAttribute('name') || FD_NAME[k];
    const text = this.getAttribute('text'), note = this.getAttribute('note');
    let h;
    clearTimeout(this._slow); this.removeAttribute('data-slow');
    if (kind === 'loading') {
      h = `<div class="sk" role="status" aria-busy="true" aria-label="Getting the latest from Friday"><i></i><i></i><i></i>`
        + `<div class="slow" part="slow">Taking longer than usual. Friday is checking the connection.</div></div>`;
      const ms = parseInt(this.getAttribute('slow-after') || '4000', 10);
      this._slow = setTimeout(() => this.setAttribute('data-slow', ''), ms);
    } else if (kind === 'stale') {
      const since = this.getAttribute('since') || '';
      h = `<div class="st hatch" role="status">${fdIcon('stale', 'var(--_text)', 24)}<div><b>${fdEsc(text || `Data from ${since}`)}</b>`
        + `<small>${fdEsc(note || 'Not live. This updates when the connection is back.')}</small></div></div>`;
    } else if (kind === 'fixing') {
      h = `<div class="st">${fdIcon('fix', 'var(--_fault)', 24)}<div><b>${fdEsc(text || 'Friday is fixing something')}</b>`
        + `<small><span class="dot" style="background:var(--_${k})"></span>${fdEsc(name)} · ${fdEsc(note || 'not yours')}</small></div></div>`;
    } else {
      h = `<div class="st empty">${fdIcon('check', 'var(--_text)', 24)}<div><b>${fdEsc(text || 'Everything is running on its own.')}</b>${note ? `<small>${fdEsc(note)}</small>` : ''}</div></div>`;
    }
    this.shadowRoot.innerHTML = `<style>${FD_CSS}${STATE_CSS}</style>${h}`;
  }
}
