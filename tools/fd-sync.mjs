#!/usr/bin/env node
// Friday DS · keeps the fd-* components in step with the tokens. No dependencies (Node ≥ 18).
//   node tools/fd-sync.mjs [--from <dir with the DTCG tokens/*.json>]
// 1. (--from) copies the token files into fd-tokens/tokens/ (the DS source of truth is Friday's state/ds/tokens/).
// 2. builds the token table (base + dark + light) and writes fd-tokens/fd-tokens.css (a page stylesheet: dark on :root,
//    paper light on [data-theme=light]).
// 3. pastes tools/fd-shared.js with the table into every fd-*/fd-*.js between the fd-shared markers.
// 4. refreshes the inlined copy inside every fd-*/example.html, and writes playground/standalone.html (every component
//    inlined, so it opens from disk or from any static host).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOK = path.join(ROOT, 'fd-tokens/tokens');
const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
if (from) for (const f of fs.readdirSync(from).filter((f) => f.endsWith('.json'))) fs.copyFileSync(path.join(from, f), path.join(TOK, f));
const J = (f) => JSON.parse(fs.readFileSync(path.join(TOK, f), 'utf8'));
const C = { dark: J('color.dark.json').color, light: J('color.light.json').color };
const type = J('type.json').font, space = J('space.json').space, shape = J('shape.json'), size = J('size.json').size,
  elev = J('elevation.json'), motion = J('motion.json'), grid = J('grid.json').grid;
const leaves = (o) => Object.entries(o || {}).filter(([k]) => !k.startsWith('$'));
const px = (t) => `${t.$value.value}${t.$value.unit}`;
const ms = (t) => `${t.$value.value}ms`;

const colour = (th) => {
  const c = C[th], v = {};
  const res = (t) => {
    if (typeof t.$value === 'string') { const p = t.$value.replace(/[{}]/g, '').split('.').slice(1); let o = c; for (const k of p) o = o[k]; return res(o); }
    return t.$value.hex;
  };
  for (const [k, t] of leaves(c.neutral)) v[k] = res(t);
  for (const [k, t] of leaves(c.mark)) v[k] = res(t);
  for (const [k, t] of leaves(c['mark-dim'])) v[`${k}-dim`] = res(t);
  for (const [k, t] of leaves(c.state)) v[k] = res(t);
  v.glow = res(c.role.glow); v.fault = res(c.role.fault);
  // effects that differ per theme (S4 specimen): panel shadow, the primary button's glow, the breath halo, the texture
  if (th === 'dark') {
    v['shadow-panel'] = elev.shadow.panel.$value.map((s) => `${s.inset ? 'inset ' : ''}${s.offsetX.value}px ${s.offsetY.value}px ${s.blur.value}px ${s.spread.value}px ${s.color}`).join(',');
    v['btn-glow'] = `0 0 ${elev.shadow.glow.$value.blur.value}px color-mix(in srgb,${v.glow} 70%,transparent)`;
    Object.assign(v, { 'halo-o': '.8', 'halo-blur': '3px', paper: '0', grain: String(elev.texture.grain.$value) });
  } else {
    v['shadow-panel'] = `0 1px 0 ${v.raised} inset,0 6px 16px rgba(60,45,25,.08)`;
    v['btn-glow'] = `0 0 0 2px color-mix(in srgb,${v.amb} 30%,transparent)`;
    Object.assign(v, { 'halo-o': '.6', 'halo-blur': '1.5px', paper: String(elev.texture['paper-fibre'].$value), grain: '0' });
  }
  return v;
};
const base = {};
base.ff = type.family.text.$value.map((f) => (/\s/.test(f) || !f.includes('-') && f !== 'sans-serif' ? `'${f}'` : f)).join(',');
for (const [k, t] of leaves(type.size)) base[`fs-${k}`] = px(t);
for (const [k, t] of leaves(type.weight)) base[`fw-${k}`] = String(t.$value);
for (const [k, t] of leaves(type.leading)) base[`lh-${k}`] = String(t.$value);
base['tr-label'] = `${type.tracking.label.$value}em`;
for (const [k, t] of leaves(space)) base[`sp-${k}`] = px(t);
for (const [k, t] of leaves(shape.radius)) base[`r-${k}`] = px(t);
for (const [k, t] of leaves(shape.stroke)) base[`st-${k}`] = t.$type === 'number' ? String(t.$value) : px(t);
for (const [k, t] of leaves(size)) base[`sz-${k}`] = px(t);
for (const [k, t] of leaves(motion.duration)) base[`d-${k}`] = ms(t);
for (const [k, t] of leaves(motion.easing)) base[`e-${k}`] = `cubic-bezier(${t.$value.join(',')})`;
for (const [k, t] of leaves(motion.rule)) base[t.$type === 'duration' ? `d-${k}` : `rule-${k}`] = t.$type === 'duration' ? ms(t) : String(t.$value);
base['grid-max'] = px(grid['desktop-max']); base['grid-gutter'] = px(grid['phone-gutter']); base['grid-gap'] = px(grid.gap);
const T = { base, dark: colour('dark'), light: colour('light') };

// 2 · page stylesheet
const decl = (o) => Object.entries(o).map(([k, v]) => `  --fd-${k}: ${v};`).join('\n');
fs.writeFileSync(path.join(ROOT, 'fd-tokens/fd-tokens.css'), `@import url('https://fonts.googleapis.com/css2?family=Figtree:wght@400;500;600&display=swap');
/* Friday DS tokens as CSS custom properties. GENERATED by tools/fd-sync.mjs from fd-tokens/tokens/*.json: do not edit.
   Dark is the default; <html data-theme="light"> (or any ancestor) switches to paper light. Every fd-* component reads these.
   The import above loads Figtree (the chosen face), so a page that uses this file never falls back to a stock face (S5 lens 2). */
:root, [data-theme=dark] {\n${decl(base)}\n${decl(T.dark)}\n  color-scheme: dark;\n}
[data-theme=light] {\n${decl(T.light)}\n  color-scheme: light;\n}
/* usage-gauge in the Friday language (S5 component 7e): its own colour hooks fed from the tokens. Amber is the one attention
   colour, so only 'near the limit, slow down' is amber (he can still act); at the limit there is nothing to do until the reset, so
   it is drawn in the text colour on a spent grey track: plain and readable, not an alarm and not faint (S5 r2 lenses 2, 3, 4,
   6, 8, 11); never red; idle is never a company colour (L4). The gauge's own stale badge is still its "!": a later patch. */
usage-gauge {
  --ug-weekly-color: var(--fd-text); --ug-session-color: var(--fd-text); --ug-tick-color: var(--fd-muted);
  --ug-tick-ahead-color: var(--fd-amb); --ug-dot-color: var(--fd-text); --ug-dot-empty-color: var(--fd-text-dim);
  --ug-track-color: var(--fd-line); --ug-warn-color: var(--fd-amb); --ug-critical-color: var(--fd-text);
  --ug-critical-track-color: var(--fd-text-dim); --ug-idle-color: var(--fd-muted);
  --ug-monogram-color: var(--fd-text); --ug-monogram-muted-color: var(--fd-muted); --ug-background: var(--fd-surface);
  font-family: var(--fd-ff);
}
`);

// 3 · shared block into every component
const shared = fs.readFileSync(path.join(ROOT, 'tools/fd-shared.js'), 'utf8').replace('/*@TOKENS@*/ {}', JSON.stringify(T));
const B = '// fd-shared:begin (generated by tools/fd-sync.mjs from tools/fd-shared.js and fd-tokens/tokens; do not edit inside)';
const E = '// fd-shared:end';
const comps = fs.readdirSync(ROOT).filter((d) => /^fd-/.test(d) && fs.existsSync(path.join(ROOT, d, `${d}.js`)));
for (const d of comps) {
  const f = path.join(ROOT, d, `${d}.js`); let s = fs.readFileSync(f, 'utf8');
  const i = s.indexOf('// fd-shared:begin'), j = s.indexOf(E);
  if (i < 0 || j < 0) { console.error(`${d}: no fd-shared markers`); process.exitCode = 1; continue; }
  s = s.slice(0, i) + B + '\n' + shared.trim() + '\n' + s.slice(j);
  if (s.includes('</' + 'script')) { console.error(`${d}: contains a closing script tag`); process.exitCode = 1; }
  fs.writeFileSync(f, s);
  // 4 · the example's inlined copy
  const ex = path.join(ROOT, d, 'example.html');
  if (fs.existsSync(ex)) {
    let h = fs.readFileSync(ex, 'utf8');
    const a = h.indexOf('<!-- fd-inline:begin -->'), b = h.indexOf('<!-- fd-inline:end -->');
    if (a >= 0 && b >= 0) { h = h.slice(0, a) + '<!-- fd-inline:begin -->\n<script type="module">\n' + s + '\n</script>\n' + h.slice(b); fs.writeFileSync(ex, h); }
  }
  console.log(d);
}
// every playground page gets a standalone copy (index.html → standalone.html, x.html → x-standalone.html)
for (const pgName of fs.readdirSync(path.join(ROOT, 'playground')).filter((f) => f.endsWith('.html') && !/standalone/.test(f))) {
  const pg = path.join(ROOT, 'playground', pgName);
  let h = fs.readFileSync(pg, 'utf8');
  h = h.replace(/<script type="module" src="\.\.\/([a-z][a-z-]+)\/\1\.js"><\/script>/g, (_, d) => `<script type="module">\n${fs.readFileSync(path.join(ROOT, d, `${d}.js`), 'utf8')}\n</script>`);
  h = h.replace('<link rel="stylesheet" href="../fd-tokens/fd-tokens.css">', `<style>\n${fs.readFileSync(path.join(ROOT, 'fd-tokens/fd-tokens.css'), 'utf8')}</style>`);
  h = h.replace('<!-- standalone:note -->', '<!-- GENERATED by tools/fd-sync.mjs from playground/index.html: every component inlined. Edit index.html. -->');
  const outName = pgName === 'index.html' ? 'standalone.html' : pgName.replace(/\.html$/, '-standalone.html');
  fs.writeFileSync(path.join(ROOT, 'playground', outName), h);
  console.log('playground/' + outName);
}
console.log(`tokens: ${Object.keys(base).length} base, ${Object.keys(T.dark).length} per theme`);
